#[serde(deny_unknown_fields)]
struct SalesCampaignGetInput {
    campaign_id: Uuid,
}

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
struct SalesCampaignAddTargetInput {
    /// Stable printable ASCII key (16–128 characters) for replaying this mutation.
    idempotency_key: String,
    campaign_id: Uuid,
    /// UUID returned by CRM company search/get; company names are not accepted.
    company_id: Uuid,
    /// UUID returned by CRM contact search/get for this company.
    contact_id: Uuid,
    /// Exact recipient UUID shown on that contact's CRM email record.
    email_address_id: Uuid,
}

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
struct SalesCampaignCreateMessageInput {
    /// Stable printable ASCII key (16–128 characters) for replaying this mutation.
    idempotency_key: String,
    campaign_id: Uuid,
    target_id: Uuid,
    subject: String,
    body_text: String,
    body_html: Option<String>,
    /// Optional immutable template-version UUID from template tools.
    template_version_id: Option<Uuid>,
    /// Template variables for this target. Public booking and unsubscribe URLs
    /// are server-owned and must not be supplied here.
    variables: Option<serde_json::Map<String, serde_json::Value>>,
    /// Set true only to create a deliberate follow-up after a prior message
    /// was accepted by the provider; accepted targets otherwise stay read-only.
    #[serde(default)]
    explicit_follow_up: bool,
}

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
enum EditableSalesCampaignStage {
    Research,
    Draft,
    Review,
}

impl EditableSalesCampaignStage {
    fn as_str(&self) -> &'static str {
        match self {
            Self::Research => "research",
            Self::Draft => "draft",
            Self::Review => "review",
        }
    }
}

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
struct SalesCampaignMoveStageInput {
    /// Stable printable ASCII key (16–128 characters) for replaying this mutation.
    idempotency_key: String,
    campaign_id: Uuid,
    target_id: Uuid,
    /// Writable stages only; later send results are derived from the outbound.
    stage: EditableSalesCampaignStage,
    expected_target_version: i64,
}

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
struct SalesCampaignQueueInput {
    /// Stable printable ASCII key (16–128 characters) for replaying the same batch job.
    idempotency_key: String,
    campaign_id: Uuid,
    target_id: Uuid,
    outbound_message_id: Uuid,
    /// Must equal the exact payload hash of the current frozen outbound message.
    expected_payload_hash: String,
    expected_target_version: i64,
}

#[derive(Debug, Serialize, JsonSchema)]
