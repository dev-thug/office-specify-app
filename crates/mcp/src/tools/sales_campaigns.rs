#[serde(deny_unknown_fields)]
struct SalesCampaignCreateInput {
    /// Stable printable ASCII key (16–128 characters) for replaying this create.
    idempotency_key: String,
    name: String,
    objective: Option<String>,
    /// Optional meeting type UUID. Booking URLs are generated by the server
    /// when a selected template uses the server-owned booking variable.
    meeting_type_id: Option<Uuid>,
}

