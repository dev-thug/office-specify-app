//! templates module domain types (spec §6 — owned by the module worker).
//!
//! §8.1 allowlist renderer: `template_versions` carry immutable content and a
//! `variable_schema` (JSON-Schema-shaped object) declaring every variable the
//! template may use. Substitution is identifier lookup only — the dotted
//! names are opaque identifiers, never object navigation or expressions
//! (§8.1). No arbitrary expressions, file access or function calls.
//!
//! - Placeholders are `{{ name }}` where `name` is a declared identifier.
//! - Undeclared placeholder in the template body → hard error.
//! - Missing required variable → `TEMPLATE_VARIABLE_MISSING`.
//! - Values substituted into HTML are HTML-escaped; values substituted into
//!   the subject may not contain CR/LF (header injection).
//! - System-generated URLs (`compliance.unsubscribe_url`,
//!   `meeting.booking_url`) are resolved server-side; user input can never
//!   supply them (§8.1: "시스템 생성 URL은 사용자가 덮어쓸 수 없다").

use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// Variable names the server injects at render/freeze time. Callers may
/// never pass values for these.
pub const SYSTEM_VARIABLES: &[&str] = &["compliance.unsubscribe_url", "meeting.booking_url"];

/// Deterministic preview values used by the render endpoint so a preview
/// never mints a real capability URL.
pub const PREVIEW_UNSUBSCRIBE_URL: &str = "https://preview.invalid/public/v1/unsubscribe/preview";
pub const PREVIEW_BOOKING_URL: &str = "https://preview.invalid/public/v1/booking/preview";

/// One declared template variable (subset of JSON Schema, B.3.5).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VariableSpec {
    pub name: String,
    pub required: bool,
    pub max_length: Option<usize>,
    pub default: Option<String>,
    /// `format: "uri"` — the value must be an http(s) URL.
    pub format_uri: bool,
}

/// Errors surfaced by schema parsing / rendering. The application layer
/// maps these to `VALIDATION_FAILED` / `TEMPLATE_VARIABLE_MISSING`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TemplateError {
    /// `variable_schema` is not a supported shape.
    InvalidSchema(String),
    /// `{{ ... }}` content that is not a bare identifier.
    UnsupportedExpression(String),
    /// Placeholder used in the template but not declared in the schema.
    UndeclaredVariable(String),
    /// Declared+required variable without a supplied value/default.
    MissingRequired(String),
    /// Caller tried to supply a system-owned variable.
    SystemVariableSupplied(String),
    /// Value exceeded `maxLength`.
    ValueTooLong { name: String, max: usize },
    /// Value is not a string / violates `format`.
    InvalidValue { name: String, reason: String },
    /// CR/LF in a header-context value (subject line).
    HeaderBreak(String),
    /// Dangerous HTML constructs detected in a stored body.
    DangerousHtml,
}

impl std::fmt::Display for TemplateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidSchema(m) => write!(f, "invalid variable_schema: {m}"),
            Self::UnsupportedExpression(s) => {
                write!(f, "template expression is not allowed: {s}")
            }
            Self::UndeclaredVariable(n) => {
                write!(f, "variable '{n}' is not declared in variable_schema")
            }
            Self::MissingRequired(n) => write!(f, "required variable '{n}' has no value"),
            Self::SystemVariableSupplied(n) => {
                write!(f, "variable '{n}' is generated by the system")
            }
            Self::ValueTooLong { name, max } => {
                write!(f, "variable '{name}' exceeds maxLength {max}")
            }
            Self::InvalidValue { name, reason } => {
                write!(f, "variable '{name}' has an invalid value: {reason}")
            }
            Self::HeaderBreak(n) => {
                write!(f, "variable '{n}' must not contain CR/LF in this context")
            }
            Self::DangerousHtml => write!(f, "body_html contains disallowed constructs"),
        }
    }
}

impl std::error::Error for TemplateError {}

/// Variable-name charset: `alpha [alnum_]* (. alpha [alnum_]*)*`. Dots are
/// part of the identifier (§8.1), not navigation.
fn valid_var_name(name: &str) -> bool {
    fn segment(s: &str) -> bool {
        !s.is_empty()
            && s.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
            && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
    }
    !name.is_empty() && name.split('.').all(segment)
}

/// Parse + validate `variable_schema` (B.3.5 shape). Supported: `type:
/// "object"`, `properties` (each `{type:"string", maxLength?, format?, default?}`),
/// `required` (subset of properties), `additionalProperties` must be absent or
/// `false` (the renderer is an allowlist).
pub fn parse_variable_schema(
    schema: &serde_json::Value,
) -> Result<Vec<VariableSpec>, TemplateError> {
    let invalid = |m: &str| TemplateError::InvalidSchema(m.to_string());
    let obj = schema
        .as_object()
        .ok_or_else(|| invalid("schema must be a JSON object"))?;
    const ROOT_KEYS: &[&str] = &["type", "properties", "required", "additionalProperties"];
    if let Some(key) = obj.keys().find(|key| !ROOT_KEYS.contains(&key.as_str())) {
        return Err(invalid(&format!("unsupported schema keyword '{key}'")));
    }
    if let Some(t) = obj.get("type")
        && t.as_str() != Some("object")
    {
        return Err(invalid("only type \"object\" is supported"));
    }
    match obj.get("additionalProperties") {
        Some(v) if v.as_bool() != Some(false) => {
            return Err(invalid("additionalProperties must be false"));
        }
        _ => {}
    }
    let mut specs = BTreeMap::<String, VariableSpec>::new();
    let props = match obj.get("properties") {
        None => serde_json::Map::new(),
        Some(v) => v
            .as_object()
            .ok_or_else(|| invalid("properties must be an object"))?
            .clone(),
    };
    for (name, def) in &props {
        if !valid_var_name(name) {
            return Err(invalid(&format!("invalid variable name '{name}'")));
        }
        let d = def
            .as_object()
            .ok_or_else(|| invalid(&format!("property '{name}' must be an object")))?;
        const PROPERTY_KEYS: &[&str] = &["type", "maxLength", "format", "default"];
        if let Some(key) = d.keys().find(|key| !PROPERTY_KEYS.contains(&key.as_str())) {
            return Err(invalid(&format!(
                "property '{name}': unsupported schema keyword '{key}'"
            )));
        }
        if let Some(t) = d.get("type")
            && t.as_str() != Some("string")
        {
            return Err(invalid(&format!(
                "property '{name}': only type \"string\" is supported"
            )));
        }
        let max_length = match d.get("maxLength") {
            None => None,
            Some(v) => Some(
                v.as_u64()
                    .filter(|n| *n > 0)
                    .ok_or_else(|| invalid(&format!("property '{name}': bad maxLength")))?
                    as usize,
            ),
        };
        let format_uri = match d.get("format") {
            None => false,
            Some(v) => match v.as_str() {
                Some("uri") => true,
                _ => return Err(invalid(&format!("property '{name}': unsupported format"))),
            },
        };
        let default = match d.get("default") {
            None => None,
            Some(v) => Some(
                v.as_str()
                    .ok_or_else(|| {
                        invalid(&format!("property '{name}': default must be a string"))
                    })?
                    .to_string(),
            ),
        };
        if default.is_some() && SYSTEM_VARIABLES.contains(&name.as_str()) {
            return Err(invalid(&format!(
                "system variable '{name}' cannot define a default"
            )));
        }
        specs.insert(
            name.clone(),
            VariableSpec {
                name: name.clone(),
                required: false,
                max_length,
                default,
                format_uri,
            },
        );
    }
    if let Some(req) = obj.get("required") {
        let list = req
            .as_array()
            .ok_or_else(|| invalid("required must be an array"))?;
        for r in list {
            let name = r
                .as_str()
                .ok_or_else(|| invalid("required entries must be strings"))?;
            match specs.get_mut(name) {
                Some(s) => s.required = true,
                None => {
                    return Err(invalid(&format!(
                        "required variable '{name}' is not in properties"
                    )));
                }
            }
        }
    }
    Ok(specs.into_values().collect())
}

/// Canonical byte form used for `content_hash`/`payload_hash` (hashed by the
/// caller with SHA-256). Fields are separated by 0x1f so concatenation
/// cannot alias.
pub fn canonical_fields<'a>(fields: impl IntoIterator<Item = &'a str>) -> Vec<u8> {
    fields
        .into_iter()
        .collect::<Vec<_>>()
        .join("\u{1f}")
        .into_bytes()
}

/// Rendered output of a template/draft.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Rendered {
    pub subject: String,
    pub body_text: String,
    pub body_html: Option<String>,
    /// Non-fatal notes (unused declared vars, ignored inputs, preview notes).
    pub warnings: Vec<String>,
}

/// The `{{ name }}` grammar. `html` selects value escaping, `header`
/// additionally forbids CR/LF.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Ctx {
    Header,
    Text,
    Html,
}

fn render_part(
    template: &str,
    specs: &BTreeMap<String, VariableSpec>,
    values: &BTreeMap<String, String>,
    ctx: Ctx,
) -> Result<String, TemplateError> {
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(open) = rest.find("{{") {
        out.push_str(&rest[..open]);
        let after = &rest[open + 2..];
        let Some(close) = after.find("}}") else {
            return Err(TemplateError::UnsupportedExpression("unclosed '{{'".into()));
        };
        let name = after[..close].trim();
        if !valid_var_name(name) {
            return Err(TemplateError::UnsupportedExpression(name.to_string()));
        }
        if !specs.contains_key(name) {
            return Err(TemplateError::UndeclaredVariable(name.to_string()));
        }
        let value = match values.get(name) {
            Some(value) => value.clone(),
            None if SYSTEM_VARIABLES.contains(&name) => {
                return Err(TemplateError::MissingRequired(name.to_string()));
            }
            None => String::new(),
        };
        if ctx == Ctx::Header && (value.contains('\r') || value.contains('\n')) {
            return Err(TemplateError::HeaderBreak(name.to_string()));
        }
        out.push_str(&match ctx {
            Ctx::Html => html_escape(&value),
            _ => value,
        });
        rest = &after[close + 2..];
    }
    // A lone '}}' outside a placeholder is literal text — allowed.
    out.push_str(rest);
    Ok(out)
}

/// RFC-3986-free conservative URI check for `format: "uri"`.
fn valid_uri(v: &str) -> bool {
    (v.starts_with("https://") || v.starts_with("http://"))
        && !v.chars().any(char::is_whitespace)
        && v.len() <= 2048
}

/// HTML-escape a substituted value (§8.1).
pub fn html_escape(v: &str) -> String {
    let mut out = String::with_capacity(v.len());
    for c in v.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#x27;"),
            _ => out.push(c),
        }
    }
    out
}

/// Resolve the value of one variable for render/freeze. `system_values`
/// holds server-injected values (unsubscribe/booking URLs).
fn resolve(
    spec: &VariableSpec,
    variables: &serde_json::Map<String, serde_json::Value>,
    system_values: &BTreeMap<String, String>,
) -> Result<Option<String>, TemplateError> {
    if SYSTEM_VARIABLES.contains(&spec.name.as_str()) {
        return Ok(system_values.get(&spec.name).cloned());
    }
    if let Some(v) = system_values.get(&spec.name) {
        return Ok(Some(v.clone()));
    }
    if let Some(v) = variables.get(&spec.name) {
        let s = match v {
            serde_json::Value::String(s) => s.clone(),
            other => {
                return Err(TemplateError::InvalidValue {
                    name: spec.name.clone(),
                    reason: format!("must be a string, got {}", type_name(other)),
                });
            }
        };
        return Ok(Some(s));
    }
    if let Some(d) = &spec.default {
        return Ok(Some(d.clone()));
    }
    if spec.required {
        return Err(TemplateError::MissingRequired(spec.name.clone()));
    }
    Ok(None)
}

fn type_name(v: &serde_json::Value) -> &'static str {
    match v {
        serde_json::Value::Null => "null",
        serde_json::Value::Bool(_) => "boolean",
        serde_json::Value::Number(_) => "number",
        serde_json::Value::String(_) => "string",
        serde_json::Value::Array(_) => "array",
        serde_json::Value::Object(_) => "object",
    }
}

/// Render `subject`/`body_text`/`body_html` against declared `specs`.
/// `variables` are caller-supplied samples/values; `system_values` are
/// server-injected (system variables can never come from `variables`).
pub fn render(
    specs: &[VariableSpec],
    subject: &str,
    body_text: &str,
    body_html: Option<&str>,
    variables: &serde_json::Map<String, serde_json::Value>,
    system_values: &BTreeMap<String, String>,
) -> Result<Rendered, TemplateError> {
    if body_html.is_some_and(is_dangerous_html) {
        return Err(TemplateError::DangerousHtml);
    }
    let by_name: BTreeMap<String, VariableSpec> =
        specs.iter().map(|s| (s.name.clone(), s.clone())).collect();

    let mut warnings = Vec::new();
    // Caller may not supply system-owned variables (§8.1).
    for name in variables.keys() {
        if SYSTEM_VARIABLES.contains(&name.as_str()) {
            return Err(TemplateError::SystemVariableSupplied(name.clone()));
        }
        if !by_name.contains_key(name) {
            warnings.push(format!(
                "supplied variable '{name}' is not declared — ignored"
            ));
        }
    }

    // Resolve every declared variable once.
    let mut values = BTreeMap::new();
    for spec in specs {
        if let Some(v) = resolve(spec, variables, system_values)? {
            if let Some(max) = spec.max_length
                && v.chars().count() > max
            {
                return Err(TemplateError::ValueTooLong {
                    name: spec.name.clone(),
                    max,
                });
            }
            if spec.format_uri && !valid_uri(&v) {
                return Err(TemplateError::InvalidValue {
                    name: spec.name.clone(),
                    reason: "must be an http(s) URI".into(),
                });
            }
            values.insert(spec.name.clone(), v);
        }
    }

    let rendered_subject = render_part(subject, &by_name, &values, Ctx::Header)?;
    let rendered_text = render_part(body_text, &by_name, &values, Ctx::Text)?;
    let rendered_html = body_html
        .map(|h| render_part(h, &by_name, &values, Ctx::Html))
        .transpose()?;

    // Warn on declared-but-unused variables (checked against all parts).
    for spec in specs {
        let needle = format!("{{{{{}}}}}", spec.name);
        let needle_sp = format!("{{{{ {} }}}}", spec.name);
        let used = subject.contains(&needle)
            || subject.contains(&needle_sp)
            || body_text.contains(&needle)
            || body_text.contains(&needle_sp)
            || body_html.is_some_and(|h| h.contains(&needle) || h.contains(&needle_sp));
        if !used {
            warnings.push(format!("declared variable '{}' is not used", spec.name));
        }
    }

    Ok(Rendered {
        subject: rendered_subject,
        body_text: rendered_text,
        body_html: rendered_html,
        warnings,
    })
}

/// §8.1 "위험 HTML" guard applied at version-create and freeze time. This is
/// a conservative substring scan, not a parser — anything it cannot vouch
/// for is rejected.
pub fn is_dangerous_html(html: &str) -> bool {
    let lower = html.to_lowercase();
    const FORBIDDEN_TAGS: &[&str] = &[
        "<script",
        "<img",
        "<picture",
        "<iframe",
        "<object",
        "<embed",
        "<form",
        "<meta",
        "<link",
        "<base",
        "<svg",
        "<style",
        "<applet",
        "<frame",
        "<frameset",
        "<audio",
        "<video",
        "<source",
        "<track",
    ];
    if FORBIDDEN_TAGS.iter().any(|t| lower.contains(t)) {
        return true;
    }
    if lower.contains("javascript:") || lower.contains("data:text/html") || lower.contains("srcdoc")
    {
        return true;
    }
    if lower.contains(" style=")
        || lower.starts_with("style=")
        || lower.contains("url(")
        || lower.contains("srcset=")
        || lower.contains("&#")
        || lower.contains("&colon;")
    {
        return true;
    }
    // Event-handler attributes: on<word>=
    let bytes = lower.as_bytes();
    let mut i = 0;
    while i + 2 < bytes.len() {
        if bytes[i] == b'o' && bytes[i + 1] == b'n' {
            let mut j = i + 2;
            while j < bytes.len() && (bytes[j].is_ascii_alphanumeric() || bytes[j] == b'_') {
                j += 1;
            }
            if j > i + 2 {
                let mut k = j;
                while k < bytes.len() && bytes[k].is_ascii_whitespace() {
                    k += 1;
                }
                if k < bytes.len() && bytes[k] == b'=' {
                    return true;
                }
            }
        }
        i += 1;
    }
    false
}

/// Reject CR/LF in fields that end up in message headers (§8.1 "헤더 줄바꿈").
pub fn contains_header_break(v: &str) -> bool {
    v.contains('\r') || v.contains('\n')
}

/// Whether the template references one declared identifier in subject, text,
/// or HTML. The parser accepts only the same exact placeholder grammar as
/// [`render`]; dotted names stay opaque identifiers.
pub fn uses_variable(name: &str, subject: &str, body_text: &str, body_html: Option<&str>) -> bool {
    fn contains(template: &str, name: &str) -> bool {
        let mut rest = template;
        while let Some(open) = rest.find("{{") {
            let after = &rest[open + 2..];
            let Some(close) = after.find("}}") else {
                return false;
            };
            if after[..close].trim() == name {
                return true;
            }
            rest = &after[close + 2..];
        }
        false
    }
    contains(subject, name)
        || contains(body_text, name)
        || body_html.is_some_and(|html| contains(html, name))
}

