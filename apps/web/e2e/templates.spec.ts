import { expect, test } from "@playwright/test";

test("template create, version save, reload, selection and variable preview use real API IDs", async ({ page }) => {
  await page.goto("/login");
  await page.locator("#login-email").fill(process.env.E2E_ADMIN_EMAIL!);
  await page.locator("#login-password").fill(process.env.E2E_ADMIN_PASSWORD!);
  await page.locator('button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\/dashboard/);
  await page.goto("/app/templates");
  await page.getByRole("button", { name: "New template", exact: true }).click();
  const create = page.getByRole("dialog");
  const name = "Template regression " + crypto.randomUUID();
  await create.getByLabel("Template name", { exact: true }).fill(name);
  await create.getByRole("button", { name: "Create", exact: true }).click();
  await expect(page).toHaveURL(/\/app\/templates\/[0-9a-f-]{36}$/);
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  for (const no of [1, 2]) {
    await page.getByRole("button", { name: "New version", exact: true }).click();
    const editor = page.getByRole("dialog");
    await editor.getByLabel("Subject", { exact: true }).fill("Version " + no);
    await editor.getByLabel("Body (text)", { exact: true }).fill(no === 1 ? "Hello {{contact.name}}" : "Saved body 2");
    await editor.getByRole("button", { name: "Save version", exact: true }).click();
    await expect(editor).toHaveCount(0);
    await expect(page.getByText(no === 1 ? "Hello {{contact.name}}" : "Saved body 2", { exact: true })).toBeVisible();
  }
  await page.reload();
  await expect(page.getByText("Saved body 2", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^v1/ }).click();
  await expect(page.getByText("Hello {{contact.name}}", { exact: true })).toBeVisible();
  await page.getByLabel("Sample variables (JSON)", { exact: true }).fill(JSON.stringify({"contact.name":"Office QA"}));
  await page.getByRole("button", { name: "Render", exact: true }).click();
  await expect(page.getByText("Hello Office QA", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Template list", exact: true }).click();
  const row = page.getByRole("row").filter({ hasText: name });
  await expect(row).toContainText("v2");
  await row.getByRole("link", { name, exact: true }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  await expect(page.getByText("Saved body 2", { exact: true })).toBeVisible();
  await page.screenshot({path:"test-artifacts/template-fixed.png", fullPage:true});
});

test("visual email authoring round-trips HTML, inserts presets and keeps samples out of saved content", async ({ page }) => {
  await page.goto("/login");
  await page.locator("#login-email").fill(process.env.E2E_ADMIN_EMAIL!);
  await page.locator("#login-password").fill(process.env.E2E_ADMIN_PASSWORD!);
  await page.locator('button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\/dashboard/);
  await page.goto("/app/templates");
  await page.getByRole("button", {name:"New template",exact:true}).click();
  const create = page.getByRole("dialog");
  const name = "Visual email QA " + crypto.randomUUID();
  await create.getByLabel("Template name", {exact:true}).fill(name);
  await create.getByRole("button", {name:"Create",exact:true}).click();
  await expect(page).toHaveURL(/\/app\/templates\/[0-9a-f-]{36}$/);
  await page.getByRole("button", {name:"New version",exact:true}).click();
  const editor = page.getByRole("dialog");
  await editor.getByLabel("Subject", {exact:true}).fill("Meeting for {{company.name}}");
  const body = editor.getByRole("textbox", {name:"Email message",exact:true});
  await body.fill("Hello ");
  await body.press("End");
  await editor.getByRole("button", {name:"Insert Contact name",exact:true}).click();
  await body.press("End");
  await body.press("Enter");
  await editor.getByRole("button", {name:"Bold",exact:true}).click();
  await body.pressSequentially("Welcome to Office");
  await editor.getByRole("tab", {name:"HTML code",exact:true}).click();
  const code = editor.getByRole("textbox", {name:"HTML code",exact:true});
  await expect(code).toHaveValue(/<(b|strong)>Welcome to Office<\/(b|strong)>/);
  await expect(code).toHaveValue(/Hello.*\{\{contact.name\}\}/);
  const html = '<p>Hi <strong>{{contact.name}}</strong>.</p><p>Welcome to {{company.name}}.</p>';
  await code.fill(html);
  await editor.getByRole("tab", {name:"Compose",exact:true}).click();
  await expect(body.locator("strong")).toHaveText("{{contact.name}}");
  await expect(editor.getByLabel("Body (text)", {exact:true})).toHaveValue("Hi {{contact.name}}.\n\nWelcome to {{company.name}}.");
  await editor.getByRole("tab", {name:"Recipient preview",exact:true}).click();
  const preview = editor.frameLocator('iframe[title="Recipient email preview"]');
  await expect(preview.getByText("Hi Jina Kim.", {exact:true})).toBeVisible();
  await editor.getByText("Preview sample values", {exact:true}).click();
  await editor.getByLabel("Contact name sample", {exact:true}).fill("Hana Lee");
  await expect(preview.getByText("Hi Hana Lee.", {exact:true})).toBeVisible();
  await editor.getByLabel("Subject", {exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:"test-artifacts/template-recipient-preview.png",fullPage:true, animations:"disabled"});
  await editor.getByRole("tab", {name:"Compose",exact:true}).click();
  await expect(editor.getByRole("tab", {name:"Compose",exact:true})).toHaveAttribute("aria-selected", "true");
  await page.screenshot({path:"test-artifacts/template-visual-editor.png",fullPage:true, animations:"disabled"});
  const saving = page.waitForRequest(request => request.method() === "POST" && new URL(request.url()).pathname.endsWith("/versions"));
  await editor.getByRole("button", {name:"Save version",exact:true}).click();
  const saved = (await saving).postDataJSON();
  expect(saved.body_html).toBe(html);
  expect(saved.body_text).toContain("{{contact.name}}");
  expect(Object.keys(saved.variable_schema.properties).sort()).toEqual(["company.name", "contact.name"]);
  expect(JSON.stringify(saved)).not.toContain("Hana Lee");
  await expect(editor).toHaveCount(0);
  await page.reload();
  await expect(page.getByText("Hi {{contact.name}}.\n\nWelcome to {{company.name}}.", {exact:true})).toBeVisible();
});
